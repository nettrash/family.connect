#!/usr/bin/env python3
"""Generate the reaction search catalogue from pinned Unicode CLDR 49.

python3 tools/emoji/make_search.py [--source-dir /path/to/cldr-49] [--check]
Without --source-dir, downloads the ten pinned inputs to a temporary directory.
No downloads or translation services are used by clients at runtime.
"""

import argparse
import hashlib
from pathlib import Path
import re
import tempfile
import urllib.request
import xml.etree.ElementTree as ET

ROOT = Path(__file__).resolve().parents[2]
COMMIT = "96e54b273d2da4ec6fbad350ba19ff23fa24a588"
LOCALES = {
    "en": "en", "de": "de", "es": "es", "fr": "fr", "ja": "ja",
    "ru": "ru", "sr": "sr", "sr-Latn": "sr_Latn", "zh-Hans": "zh",
}


def catalogue():
    source = (ROOT / "web/text/src/emoji.rs").read_text(encoding="utf-8")
    source = source.split("pub static EMOJI_CATALOG", 1)[1].split("#[cfg(test)]", 1)[0]
    result = []
    for block in re.findall(r"emoji:\s*&\[(.*?)\]", source, re.S):
        for emoji in re.findall(r'"([^"]+)"', block):
            if emoji not in result:
                result.append(emoji)
    if not result:
        raise ValueError("No emoji found in the canonical catalogue")
    return result


def generate(source):
    emoji = catalogue()
    header = (
        "# Localised reaction names and keywords; generated by tools/emoji/make_search.py.\n"
        f"# Unicode CLDR 49, commit {COMMIT}. Unicode-3.0; see UNICODE-LICENSE.txt.\n"
        "# locale<TAB>catalogue emoji<TAB>localised name<TAB>keywords separated by |\n"
    )
    rows = []
    for locale, cldr in LOCALES.items():
        path = source / f"common/annotations/{cldr}.xml"
        entries = {}
        for entry in ET.parse(path).iter("annotation"):
            key = entry.attrib["cp"].replace("\ufe0f", "")
            kind = "name" if entry.attrib.get("type") == "tts" else "keywords"
            entries.setdefault(key, {})[kind] = entry.text or ""
        for glyph in emoji:
            entry = entries.get(glyph.replace("\ufe0f", ""), {})
            name = entry.get("name", "")
            keywords = entry.get("keywords", "")
            if not name or not keywords or "↑↑↑" in (name, keywords):
                raise ValueError(f"Missing {locale} annotations for {glyph!r}")
            if any(char in name + keywords for char in "\t\r\n"):
                raise ValueError(f"Invalid TSV annotation for {glyph!r}")
            rows.append(f"{locale}\t{glyph}\t{name}\t{keywords}\n")
    return {
        ROOT / "web/text/data/emoji-search.tsv": header + "".join(rows),
        ROOT / "web/text/data/UNICODE-LICENSE.txt": (source / "LICENSE").read_text(encoding="utf-8"),
    }


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source-dir", type=Path)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    with tempfile.TemporaryDirectory(prefix="fc-cldr-") as temporary:
        source = args.source_dir or Path(temporary)
        paths = [f"common/annotations/{loc}.xml" for loc in LOCALES.values()] + ["LICENSE"]
        manifest = ROOT / "tools/emoji/cldr-search-sources.sha256"
        hashes = dict(line.split("  ", 1)[::-1] for line in manifest.read_text(encoding="utf-8").splitlines())
        for path in paths:
            full = source / path
            if args.source_dir is None:
                url = f"https://raw.githubusercontent.com/unicode-org/cldr/{COMMIT}/{path}"
                full.parent.mkdir(parents=True, exist_ok=True)
                with urllib.request.urlopen(url, timeout=30) as response:
                    full.write_bytes(response.read())
            if hashlib.sha256(full.read_bytes()).hexdigest() != hashes[path]:
                raise ValueError(f"Source checksum mismatch: {path}")
        for path, text in generate(source).items():
            if args.check:
                if not path.exists() or path.read_text(encoding="utf-8") != text:
                    raise SystemExit(f"Stale generated file: {path.relative_to(ROOT)}")
            else:
                path.write_text(text, encoding="utf-8")
        print(f"CLDR 49: {len(catalogue())} emoji × {len(LOCALES)} locales; "
              + ("generated files verified" if args.check else "generated files written"))


if __name__ == "__main__":
    main()
