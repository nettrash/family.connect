def names(source):
    table = {}
    for entry in json.load(open(source, encoding="utf-8")).values():
        emoji = "".join(chr(int(point, 16)) for point in entry["code_points"]["fully_qualified"].split("-"))
        for name in [entry["shortname"]] + entry.get("shortname_alternates", []):
            if not name:
                continue
            bare = name.strip(":")
            if not bare or name != f":{bare}:" or any(c.isspace() or c == ":" for c in bare):
                sys.exit(f"an unexpected name in the source: {name!r}")
            if table.get(bare, emoji) != emoji:
                sys.exit(f"{name} names two different emoji")
            table[bare] = emoji
    for bare, emoji in TELEGRAM_EXTRAS.items():
        if table.get(bare, emoji) != emoji:
            sys.exit(f":{bare}: is already JoyPixels' name for something else")
        table[bare] = emoji
    return table


def main():
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    table = names(sys.argv[1])
    body = HEADER + "".join(f"{name}\t{table[name]}\n" for name in sorted(table))
    for path in [CANONICAL] + COPIES:
        full = os.path.join(ROOT, path)
        os.makedirs(os.path.dirname(full), exist_ok=True)
        with open(full, "w", encoding="utf-8", newline="\n") as out:
            out.write(body)
    print(f"{len(table)} names -> {CANONICAL} and {len(COPIES)} copies")


if __name__ == "__main__":
    main()
