#[test]
fn every_pattern_reads_as_dotnet_writes_it() {
    let format = format_description!("[year]-[month]-[day]T[hour]:[minute]:[second]");
    let mut failures = Vec::new();
    for &(name, at, pattern, expected) in VECTORS {
        let culture = if name.is_empty() {
            DateCulture::invariant()
        } else {
            DateCulture::named(name).unwrap_or_else(|| panic!("{name} is measured"))
        };
        let at = PrimitiveDateTime::parse(at, &format).expect("a vector's time");
        let written = culture.format(at, pattern);
        if written != expected {
            failures.push(format!(
                "{name:?} {at} {pattern:?}: {written:?}, .NET {expected:?}"
            ));
        }
    }
    assert!(
        failures.is_empty(),
        "{} of {}:\n{}",
        failures.len(),
        VECTORS.len(),
        failures.join("\n")
    );
}

#[test]
fn a_posix_locale_finds_its_nearest_culture() {
    for (locale, name) in [
        ("en_US.UTF-8", "en-US"),
        ("en", "en-US"),
        ("en_GB.UTF-8", "en-GB"),
        ("en_IE.utf8", "en-GB"),
        ("de_AT.UTF-8", "de-DE"),
        ("de_DE@euro", "de-DE"),
        ("es_MX.UTF-8", "es-ES"),
        ("fr_CA", "fr-FR"),
        ("ja_JP.UTF-8", "ja-JP"),
        ("ru_RU.UTF-8", "ru-RU"),
        ("sr_RS.UTF-8", "sr-Cyrl-RS"),
        ("sr_RS.UTF-8@latin", "sr-Latn-RS"),
        ("sr_RS@latin", "sr-Latn-RS"),
        ("sr-Latn-RS", "sr-Latn-RS"),
        ("zh_CN.UTF-8", "zh-CN"),
        ("zh_TW.UTF-8", "zh-CN"),
        ("C", "en-US"),
        ("POSIX", "en-US"),
        ("C.UTF-8", "en-US"),
        ("", "en-US"),
        ("it_IT.UTF-8", "en-US"),
    ] {
        assert_eq!(DateCulture::for_locale(locale).name, name, "{locale:?}");
    }
}

#[test]
fn a_culture_is_found_by_its_name_whatever_the_case() {
    assert_eq!(
        DateCulture::named("EN-gb").map(|culture| culture.name),
        Some("en-GB".to_string())
    );
    assert_eq!(DateCulture::named("pt-BR"), None);
    assert_eq!(DateCulture::named(""), Some(DateCulture::invariant()));
    let russian = DateCulture::named("ru-RU").unwrap();
    assert_eq!(russian.month_name(3), "март");
    assert_eq!(russian.month_name(0), "");
    assert_eq!(russian.month_name(13), "");
}
